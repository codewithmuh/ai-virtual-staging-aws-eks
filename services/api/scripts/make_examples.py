def empty_room_prompt(scene: Scene) -> str:
    return (
        f"Real-estate listing photo of {scene.room}. The room is completely empty: no "
        "furniture, no rugs, no curtains, no decor, no people. Eye level, wide-angle lens, "
        "straight verticals, soft natural daylight. Photorealistic, like a professional "
        "property photographer's photo."
    )


async def generate_room(settings: Settings, scene: Scene) -> tuple[bytes, str]:
    """An empty room from the provider in IMAGE_PROVIDER: Gemini, or OpenAI otherwise."""
    if settings.image_provider == "gemini":
        from google import genai
        from google.genai import types

        response = await genai.Client().aio.models.generate_content(
            model=settings.gemini_image_model,
            contents=empty_room_prompt(scene),
            config=types.GenerateContentConfig(
                response_modalities=["TEXT", "IMAGE"],
                image_config=types.ImageConfig(aspect_ratio="3:2"),
            ),
        )
        for candidate in response.candidates or []:
            for part in (candidate.content.parts if candidate.content else None) or []:
                if part.inline_data and part.inline_data.data:
                    return part.inline_data.data, settings.gemini_image_model
        raise RuntimeError(f"{settings.gemini_image_model} returned no image for {scene.id}")

    from openai import AsyncOpenAI

    result = await AsyncOpenAI().images.generate(
        model=settings.openai_image_model,
        prompt=empty_room_prompt(scene),
        size="1536x1024",
        quality="high",
        output_format="jpeg",
    )
    b64 = result.data[0].b64_json if result.data else None
    if not b64:
        raise RuntimeError(f"{settings.openai_image_model} returned no image for {scene.id}")
    return base64.b64decode(b64), settings.openai_image_model


def for_web(img: Image.Image) -> bytes:
    if img.width > WIDTH:
        img = img.resize((WIDTH, round(img.height * WIDTH / img.width)), Image.Resampling.LANCZOS)
    return images.to_jpeg(img, quality=82)


def find_image(folder: Path | None, name: str) -> Path | None:
    if folder is None:
        return None
    for ext in ("jpg", "jpeg", "png", "webp"):
        if (path := folder / f"{name}.{ext}").exists():
            return path
    return None


async def make(
    settings: Settings,
    scene: Scene,
    photos: Path | None,
    generated_by: str | None,
    staged_by: str | None,
    previous: dict[str, Any],
) -> dict[str, Any]:
    # Where the empty room came from, so the page can say: a photo, or generated and by what.
    before_path = PUBLIC / f"{scene.id}-before.jpg"
    room_model: str | None
    if photo := find_image(photos, scene.id):
        raw, room_model = photo.read_bytes(), generated_by
    elif staged_by:
        raise RuntimeError(f"no empty room {scene.id}.png or .jpg in {photos}")
    elif before_path.exists():
        raw, room_model = before_path.read_bytes(), previous.get("room_model")
    else:
        print(f"  {scene.id}: generating the empty room with {settings.image_provider}")
        raw, room_model = await generate_room(settings, scene)

    clean = images.prepare_upload(raw)
    seconds: float | None
    if staged_by:
        # Staged outside Heya: no timing to report, and the page credits the tool, not Heya.
        staged_file = find_image(photos, f"{scene.id}-staged")
        if staged_file is None:
            raise RuntimeError(f"no staged room {scene.id}-staged.png or .jpg in {photos}")
        print(f"  {scene.id}: checking the room staged with {staged_by}")
        staged_raw, seconds = staged_file.read_bytes(), None
        stager, provider, model = "external", staged_by, None
    else:
        editor = build_editor(settings)
        print(f"  {scene.id}: staging in {scene.style.value} with {editor.name}")
        started = time.perf_counter()
        staged_raw = await editor.stage(clean, scene.style)
        seconds = round(time.perf_counter() - started, 1)
        models = {"openai": settings.openai_image_model, "gemini": settings.gemini_image_model}
        stager, provider, model = "heya", editor.name, models.get(editor.name)

    original = images.open_rgb(clean)
    staged = images.match_size(staged_raw, original.size)
    score = structure_score(original, staged)
    labelled = images.open_rgb(images.add_label(staged))

    PUBLIC.mkdir(parents=True, exist_ok=True)
    before_path.write_bytes(for_web(original))
    (PUBLIC / f"{scene.id}-after.jpg").write_bytes(for_web(labelled))
    width, height = Image.open(before_path).size
    return {
        "id": scene.id,
        "title": scene.title,
        "style": scene.style.value,
        "room": "generated" if room_model else "photo",
        "room_model": room_model,
        "staged_by": stager,
        "provider": provider,
        "model": model,
        "seconds": seconds,
        "structure": {"score": score, "flagged": score < settings.structure_threshold},
        "width": width,
        "height": height,
    }


def provider_problem(settings: Settings, allow_fake: bool) -> str | None:
    """Why the image provider in .env can't make examples, or None if it can."""
    if settings.image_provider == "fake" and not allow_fake:
        return "IMAGE_PROVIDER is fake: set it to openai or gemini (and the key) in .env."
    keys = {"openai": ("OPENAI_API_KEY",), "gemini": ("GEMINI_API_KEY", "GOOGLE_API_KEY")}
    needed = keys.get(settings.image_provider, ())
    if needed and not any(os.environ.get(k) for k in needed):
        return f"IMAGE_PROVIDER is {settings.image_provider}: set {needed[0]} in .env."
    return None


async def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawTextHelpFormatter
    )
    parser.add_argument(
        "--only", help="comma-separated scene ids: " + ", ".join(s.id for s in SCENES)
    )
    parser.add_argument(
        "--force", action="store_true", help="stage again even if an example exists"
    )
    parser.add_argument(
        "--photos",
        type=Path,
        help="folder of empty rooms, <scene id>.jpg (default: examples-src/ if it exists)",
    )
    parser.add_argument(
        "--generated-by",
        metavar="NAME",
        help="the --photos are AI-generated, e.g. by ChatGPT; the page says so",
    )
    parser.add_argument(
        "--staged-by",
        metavar="NAME",
        help="use <scene id>-staged.jpg from the photos folder, staged with NAME, not the API",
    )
    parser.add_argument(
        "--allow-fake", action="store_true", help="test the pipeline with the fake model"
    )
    args = parser.parse_args()

    settings = load_settings()
    photos: Path | None = args.photos or (INBOX if INBOX.is_dir() else None)
    if args.staged_by and photos is None:
        print(f"--staged-by needs the images in {INBOX} (or --photos).", file=sys.stderr)
        return 2
    if problem := None if args.staged_by else provider_problem(settings, args.allow_fake):
        print(problem, file=sys.stderr)
        return 2

    manifest: list[dict[str, Any]] = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else []
    by_id = {e["id"]: e for e in manifest}
    wanted = set(args.only.split(",")) if args.only else {s.id for s in SCENES}
    unknown = wanted - {s.id for s in SCENES}
    if unknown:
        print(f"Unknown scene ids: {', '.join(sorted(unknown))}", file=sys.stderr)
        return 2

    failed = 0
    for scene in SCENES:
        if scene.id not in wanted or (scene.id in by_id and not args.force):
            continue
        try:
            example = await make(
                settings,
                scene,
                photos,
                args.generated_by,
                args.staged_by,
                by_id.get(scene.id, {}),
            )
        except Exception as exc:  # one failed scene shouldn't lose the others
            print(f"  {scene.id}: failed: {exc}", file=sys.stderr)
            failed += 1
            continue
        if example["structure"]["flagged"]:
            # Rule R2: a staging that moved walls or windows is no example of the product.
            print(
                f"  {scene.id}: flagged by the structure check, not used; try --force",
                file=sys.stderr,
            )
            failed += 1
            continue
        by_id[scene.id] = example
        score = example["structure"]["score"]
        took = f" in {example['seconds']} s" if example["seconds"] is not None else ""
        print(f"  {scene.id}: done{took}, structure score {score}")

    ordered = [by_id[s.id] for s in SCENES if s.id in by_id]
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps(ordered, indent=2) + "\n")
    print(f"{len(ordered)} examples in {MANIFEST.relative_to(WEB.parent.parent)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
