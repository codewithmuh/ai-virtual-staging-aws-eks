"""Make the before/after examples on the home page, with Heya's own staging pipeline.

Each empty room goes through the same steps as a real staging: metadata removed (rule R3), staged by
the image model in IMAGE_PROVIDER, structure checked (rule R2) and labelled (rule R1). Results go to
services/web/public/examples/ and services/web/src/content/examples.json, ready to commit.

    make examples                                   # the scenes that don't have an example yet
    make examples ARGS="--only bedroom --force"     # stage one again
    make examples ARGS="--generated-by Gemini"      # the empty rooms in examples-src/ are AI-made
    make examples ARGS="--generated-by Gemini --staged-by Gemini"   # and so are the staged ones

Where the empty rooms come from, in order: examples-src/<scene id>.png|jpg at the repository root
(or --photos), the "before" already on the page, or a new one generated by the same provider
(OpenAI or Gemini, with its key). With --staged-by, the staged rooms come from
examples-src/<scene id>-staged.png|jpg instead of the API; they are still checked and labelled.
The page says where each part came from.
"""

